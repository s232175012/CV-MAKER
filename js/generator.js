function downloadPDF(){
  const data = JSON.parse(localStorage.getItem('portfolioData') || '{}');
  const name = (document.getElementById('firstName')?.value || 'My') + '_' + (document.getElementById('lastName')?.value || 'CV');

  // A4 = 210mm width. We create hidden A4 clone.
  const pdfWrapper = document.createElement('div');
  pdfWrapper.style.width = '210mm';
  pdfWrapper.style.minHeight = '297mm';
  pdfWrapper.style.background = 'white';
  pdfWrapper.style.position = 'fixed';
  pdfWrapper.style.left = '-9999px';
  pdfWrapper.style.top = '0';
  pdfWrapper.style.padding = '0';
  pdfWrapper.style.margin = '0';
  pdfWrapper.className = 'preview-content template-' + currentTemplate;
  pdfWrapper.innerHTML = getTemplateHTML(data, currentTemplate);

  // Force desktop grid inside A4 - never stack
  const styleFix = document.createElement('style');
  styleFix.innerHTML = `
    *{ -webkit-print-color-adjust: exact !important; print-color-adjust: exact !important; }
    .template-pink, .template-blue, .template-sky, .template-teal { grid-template-columns: 70mm 140mm !important; display:grid !important; min-height:297mm; }
    .template-orange { grid-template-columns: 130mm 80mm !important; display:grid !important; min-height:297mm; }
    .template-gray .head { grid-template-columns: 1fr auto !important; display:grid !important; }
    .template-gray .body { grid-template-columns: 2fr 1fr !important; display:grid !important; }
    .template-purple .body, .template-yellow .body { grid-template-columns: 1fr 1fr !important; display:grid !important; }
    .preview-content { margin:0 !important; box-shadow:none !important; }
    @page { size: A4; margin: 0; }
  `;
  pdfWrapper.appendChild(styleFix);
  document.body.appendChild(pdfWrapper);

  const opt = {
    margin: 0,
    filename: `${name}_A4_${currentTemplate}.pdf`,
    image: { type: 'jpeg', quality: 1 },
    html2canvas: { 
      scale: 3, // High quality for A4
      useCORS: true,
      width: 794, // A4 at 96dpi
      windowWidth: 794,
      scrollY: 0
    },
    jsPDF: { 
      unit: 'mm', 
      format: 'a4', 
      orientation: 'portrait',
      hotfixes: ['px_scaling']
    },
    pagebreak: { mode: ['css', 'legacy'] }
  };

  html2pdf().set(opt).from(pdfWrapper).save().then(() => {
    document.body.removeChild(pdfWrapper);
  });
}

async function downloadZIP(){
  const data = JSON.parse(localStorage.getItem('portfolioData') || '{}');
  const cssText = await fetch('css/templates.css').then(r=>r.text()).catch(()=> '');
  const styleText = await fetch('css/style.css').then(r=>r.text()).catch(()=> '');
  const content = document.getElementById('livePreview').innerHTML;
  const htmlContent = `<!DOCTYPE html>
<html><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${data.firstName||'Portfolio'} Portfolio</title>
<style>${styleText}\n${cssText}\nbody{max-width:210mm;margin:0 auto} @page{size:A4;margin:0}</style>
</head><body><div class="preview-content template-${currentTemplate}" style="margin:0 auto;box-shadow:none;min-height:297mm">${content}</div></body></html>`;
  const zip = new JSZip();
  zip.file("index.html", htmlContent);
  zip.file("README.txt", `Portfolio - ${data.firstName||''} ${data.lastName||''}\nTemplate: ${currentTemplate}\nA4 PDF ready\nGenerated by BuildMyPortfolio`);
  const blob = await zip.generateAsync({type:"blob"});
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = `${data.firstName||'portfolio'}-${currentTemplate}-A4-website.zip`;
  a.click();
}